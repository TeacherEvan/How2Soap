def _glb_exported_channels(glb_path):
    """Read exported animation channels (target paths) from a GLB's JSON chunk."""
    import json
    import struct
    if not os.path.exists(glb_path):
        return None
    with open(glb_path, "rb") as fh:
        data = fh.read()
    length = struct.unpack("<I", data[12:16])[0]
    doc = json.loads(data[20:20 + length])
    exported = {}
    for anim in doc.get("animations", []):
        exported[anim.get("name", "?")] = sorted({ch["target"]["path"] for ch in anim.get("channels", [])})
    return exported


def write_action_manifest(wanted, no_export):
    """Sidecar manifest: exported (GLB-verified) channels + Blender-only curves.

    Downstream contract: the Float32Array bake MUST read the GLB for motion
    AND this manifest for Blender-only channels — never assume the GLB alone
    carries the full animation (curve offset / emission strength are absent).
    """
    actions = {}
    for name in wanted:
        exported = None if no_export else _glb_exported_channels(os.path.join(OUT, f"{name}.glb"))
        actions[name] = {
            "glb": f"public/assets/workbench/{name}.glb",
            "frames": ACTION_FRAMES[name],
            "fps": FPS,
            "exported_channels": exported,
            "blender_only_channels": BLENDER_ONLY_CHANNELS.get(name, []),
        }
    manifest = {
        "format": "workbench_actions/1",
        "contract": ("Downstream Float32Array bake MUST combine exported_channels "
                     "(from the GLB, verified above) with blender_only_channels "
                     "(from this manifest / the original Blender actions). "
                     "GLB alone does NOT carry curve-offset UV flow or emission-strength curves."),
        "actions": actions,
    }
    manifest_path = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "templates", "workbench_actions.json"))
    os.makedirs(os.path.dirname(manifest_path), exist_ok=True)
    import json
    with open(manifest_path, "w") as fh:
        json.dump(manifest, fh, indent=2)
    print(f"WROTE: {manifest_path}")


